// app/assets/frozen-marks.js holds fingerprints of the old notes and no readable words: outside its fixed header and
// key names it is hex digits only, sorted fixed-width hashes. In the private repo it must also be up to date with
// private/frozen/, and the tool is checked on a made-up note (lines and runs in, runs Mess shows anyway out).
// Nothing here prints old text: only counts. No browser.
const fs = require('node:fs'), os = require('node:os'), { join } = require('node:path'), { spawnSync } = require('node:child_process');
const root = join(__dirname, '..'), errs = [], made = [];
(async () => {
  const file = join(root, 'app/assets/frozen-marks.js');
  const t = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null; // the public copy has no app/
  if (t !== null) {
  const HEADER = '// Generated by tools/frozen-marks.mjs. Do not edit. Hashes only: see MAP.md for the format.\n';
  const m = t.match(/^([^\n]*\n)self\.MESS_FROZEN_MARKS=\{"v":2,"run":5,"minLine":6,"lines":"([0-9a-f]*)","runs":"([0-9a-f]*)"\};\n$/);
  if (!m) errs.push('frozen-marks.js is not just the header and the hash object');
  else {
    if (m[1] !== HEADER) errs.push('frozen-marks.js header is not the fixed one');
    for (const [k, s] of [['lines', m[2]], ['runs', m[3]]]) {
      if (s.length % 8) errs.push(`${k} is not whole 8-digit hashes`);
      const h = s.match(/.{8}/g) || [];
      if (h.length < 100) errs.push(`${k}: only ${h.length} hashes`);
      if (h.some((x, i) => i && h[i - 1] >= x)) errs.push(`${k} is not sorted and unique`);
    }
    // Every word in the file is from the header or the key names: nothing else can be read.
    const ok = new Set((HEADER + ' self MESS_FROZEN_MARKS v run minLine lines runs').toLowerCase().match(/[a-z]+/g));
    const rest = t.replace(m[2], '').replace(m[3], '').toLowerCase().match(/[a-z]{2,}/g) || [];
    const stray = rest.filter(w => !ok.has(w)); if (stray.length) errs.push(`${stray.length} word(s) outside the header and keys`);
  }
  }
  const tool = join(root, 'tools/frozen-marks.mjs');
  if (fs.existsSync(tool)) {
    const T = await import(tool);
    // Pinned values, so the app's copy of norm and hash can be checked against these.
    if (T.hash('') !== '811c9dc5' || T.hash('a') !== 'e40c292c' || T.hash('foobar') !== 'bf9cf968') errs.push('hash is not FNV-1a 32-bit');
    if (T.norm('  Café’s  BP: 140/90 — Raised!') !== 'cafe s bp 140 90 raised') errs.push('norm changed');
    if (T.norm('β-blocker Straße co\u00adoperate ﬁne zero\u200bwidth') !== 'beta blocker strasse cooperate fine zerowidth') errs.push('norm changed for Greek, ß, soft hyphen, ligature or zero-width');
    // Strings as the app sees them: escapes decoded, comments skipped, template literals across lines kept.
    const S = T.stringsOf("// it's a comment\nx = ['a\\u2019b', `one\ntwo ${y} three`, \"q\\tq\"]; /* don't */");
    if (JSON.stringify(S) !== JSON.stringify(['a\u2019b', 'one\ntwo   three', 'q q'])) errs.push('stringsOf: ' + JSON.stringify(S));
    const S2 = T.stringsOf("'foo\\\r\nbar', 'a\\\u2028b', 'c\\bd', 'e\\0f'");
    if (JSON.stringify(S2) !== JSON.stringify(['foobar', 'ab', 'c d', 'e f'])) errs.push('stringsOf escapes: ' + JSON.stringify(S2));
    // A made-up tree: one old note, an open statement that shares one run of it.
    const d = fs.mkdtempSync(join(os.tmpdir(), 'mess-marks-')); made.push(d);
    const note = 'Zebra lanterns hum quietly beside violet harbour walls tonight. Second sentence about purple kites flying high.';
    fs.mkdirSync(join(d, 'private/frozen/app/assets'), { recursive: true }); fs.mkdirSync(join(d, 'content/open/x'), { recursive: true }); fs.mkdirSync(join(d, 'app'));
    fs.writeFileSync(join(d, 'private/frozen/app/assets/frozen.js'), `x = { a: '${note}', b: 'short one' };`);
    fs.writeFileSync(join(d, 'content/open/x/statements.src.txt'), 'Open text: violet harbour walls tonight, second and more.');
    const r = T.build(d), has = (k, s) => new RegExp(`"${k}":"(?:.{8})*?${T.hash(s)}`).test(r.text);
    if (!has('lines', T.norm(note))) errs.push('the whole old line is not marked');
    if (!has('lines', 'zebra lanterns hum quietly beside violet harbour walls tonight')) errs.push('one sentence of the old line is not marked');
    if (has('lines', 'short one')) errs.push('a line under 6 words was marked');
    if (!has('runs', 'zebra lanterns hum quietly beside')) errs.push('a run of 5 old words is not marked');
    // Runs do not overlap (words 1-5, 6-10 ...), so the file cannot be chained back into text one word at a time.
    if (has('runs', 'lanterns hum quietly beside violet')) errs.push('an overlapping run was stored');
    // A copy at any offset is still found: the app hashes every 5 words of the student's text.
    const copy = T.marksFor('My note: zebra lanterns hum quietly beside violet harbour walls tonight second sentence about purple kites flying');
    const hits = copy.runs.filter(h => new RegExp(`"runs":"(?:.{8})*?${h}`).test(r.text)).length;
    if (hits < 2) errs.push(`a copy at another offset hit ${hits} run(s), expected 2`);
    if (has('runs', 'violet harbour walls tonight second')) errs.push('a run the open content also has was marked');
    if (!(r.leftOut > 0)) errs.push('nothing was left out as open text');
    if (/zebra|lantern|harbour|violet/i.test(r.text)) errs.push('old words reached the output');
    // The real file: up to date with private/frozen/ (private repo only).
    if (fs.existsSync(join(root, 'private/frozen'))) {
      const c = spawnSync(process.execPath, [tool, '--check'], { cwd: root, encoding: 'utf8' });
      if (c.status !== 0) errs.push('app/assets/frozen-marks.js is out of date: run node tools/frozen-marks.mjs');
    }
  }
  for (const d of made) fs.rmSync(d, { recursive: true, force: true });
  console.log('ERRS', errs);
})();
